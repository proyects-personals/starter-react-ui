/**
 * @description Defines the supported gradient types.
 * @author Steveen Cues
 * @version 2.0.0
 */
export type ThemeGradientType = "linear" | "radial" | "conic";

/**
 * @description Defines the permitted gradient directions.
 * @author Steveen Cues
 * @version 2.0.0
 */
export type ThemeGradientDirection =
  | "to-top"
  | "to-right"
  | "to-bottom"
  | "to-left"
  | "to-top-right"
  | "to-top-left"
  | "to-bottom-right"
  | "to-bottom-left";
